-- Run this in the Supabase SQL Editor to create a public read-only product catalog
-- and insert sample data for price filtering and pagination.

create table if not exists public.products (
  id bigint generated by default as identity primary key,
  name text not null unique,
  description text not null default '',
  price numeric(10, 2) not null check (price >= 0),
  image_url text,
  created_at timestamptz not null default now()
);

alter table public.products enable row level security;

-- Allow the Flutter client roles to issue read queries; the policy below controls rows.
grant select on public.products to anon, authenticated;

drop policy if exists "Products are readable by everyone" on public.products;
create policy "Products are readable by everyone"
  on public.products
  for select
  to anon, authenticated
  using (true);

